// Package schedule 用 systemd --user timer 做定时任务。
//
// 为什么不用 crontab：
//   - cron 失败只写邮件或 /var/log，用户看不到历史；
//   - systemd 有 journal（`clashgo log` 之外还能 `journalctl --user -u clashgo-sub-update`）、
//     Persistent=true 能补跑关机期间错过的触发、RandomizedDelaySec 能打散订阅请求；
//   - 与「阶段二挂 systemd」是同一套东西，不用维护两套调度。
package schedule

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

const (
	// ServiceName / TimerName 是固定的单元名，删除时按名字找，避免误删别人的 unit。
	ServiceName = "clashgo-sub-update.service"
	TimerName   = "clashgo-sub-update.timer"

	// Marker 用来标记「这个文件是 clashgo 生成的」。
	// Remove 只会删除含 Marker 的文件，避免把用户手写的同名 unit 删掉。
	Marker = "# Generated by clashgo"

	// DefaultInterval 是订阅更新默认间隔。
	DefaultInterval = 6 * time.Hour
)

// Spec 描述要生成的定时任务。
type Spec struct {
	BaseDir  string        // CLASH_BASE_DIR，写进 Environment= 让 timer 里的命令读到同一份配置
	Binary   string        // clashgo 可执行文件绝对路径
	Interval time.Duration // 更新间隔
	All      bool          // true = 更新全部订阅；false = 只更新当前订阅
}

// Dir 返回 systemd 用户单元目录 ~/.config/systemd/user。
func Dir() (string, error) {
	if xdg := os.Getenv("XDG_CONFIG_HOME"); xdg != "" {
		return filepath.Join(xdg, "systemd", "user"), nil
	}
	home := os.Getenv("HOME")
	if home == "" {
		return "", fmt.Errorf("无法确定用户主目录：$HOME 未设置")
	}
	return filepath.Join(home, ".config", "systemd", "user"), nil
}

// ServicePath / TimerPath 返回两个单元文件的路径。
func ServicePath() (string, error) {
	d, err := Dir()
	if err != nil {
		return "", err
	}
	return filepath.Join(d, ServiceName), nil
}

func TimerPath() (string, error) {
	d, err := Dir()
	if err != nil {
		return "", err
	}
	return filepath.Join(d, TimerName), nil
}

// Available 判断 systemd 用户实例是否可用。
// 只看文件系统特征，不真的去连 D-Bus，避免在非 systemd 环境里卡住。
func Available() bool {
	if _, err := os.Stat("/run/systemd/system"); err != nil {
		return false
	}
	for _, p := range []string{"/usr/bin/systemctl", "/bin/systemctl"} {
		if _, err := os.Stat(p); err == nil {
			return true
		}
	}
	return false
}

// userEnv 返回调用 systemctl --user 所需的环境。
//
// 关键坑：非交互进程里 XDG_RUNTIME_DIR 常常是空的，
// 此时 `systemctl --user` 直接报 `Failed to connect to bus: 找不到介质`。
// 补上 /run/user/<uid> 之后就能正常连上用户实例。
func userEnv() []string {
	env := os.Environ()
	if os.Getenv("XDG_RUNTIME_DIR") == "" {
		env = append(env, fmt.Sprintf("XDG_RUNTIME_DIR=/run/user/%d", os.Getuid()))
	}
	return env
}

// runUser 执行 `systemctl --user <args...>`。
func runUser(args ...string) (string, error) {
	cmd := exec.Command("systemctl", append([]string{"--user"}, args...)...)
	cmd.Env = userEnv()
	out, err := cmd.CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			return "", err
		}
		return "", fmt.Errorf("%v: %s", err, msg)
	}
	return string(out), nil
}

// calendarExpr 把「每 N 小时」翻译成 OnCalendar 表达式。
//
// 只有当间隔是整小时、且能整除 24 时才用 OnCalendar——
// 因为只有 OnCalendar 才支持 Persistent=true（关机期间错过的触发会在开机后补跑）。
// 其它间隔退回 OnUnitActiveSec，此时没有补跑语义。
func calendarExpr(d time.Duration) (string, bool) {
	if d < time.Hour {
		return "", false
	}
	h := int(d / time.Hour)
	if d != time.Duration(h)*time.Hour {
		return "", false
	}
	if h < 1 || h > 24 || 24%h != 0 {
		return "", false
	}
	return fmt.Sprintf("*-*-* 00/%d:00:00", h), true
}

// ServiceFile 生成 service 单元内容。
func (s Spec) ServiceFile() string {
	bin := s.Binary
	if bin == "" {
		bin = "clashgo"
	}
	args := "sub update"
	if s.All {
		args += " --all"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s. 执行 `clashgo sub schedule --off` 会删除本文件。\n", Marker)
	b.WriteString("[Unit]\n")
	b.WriteString("Description=clashgo 定时更新订阅\n")
	// 订阅下载需要网络；network-online.target 只在系统层存在，
	// 用户实例里引用它只是「尽量等网络就绪」，不会阻塞。
	b.WriteString("After=network-online.target\n")
	b.WriteString("Wants=network-online.target\n\n")
	b.WriteString("[Service]\n")
	b.WriteString("Type=oneshot\n")
	fmt.Fprintf(&b, "ExecStart=%s %s\n", bin, args)
	if s.BaseDir != "" {
		fmt.Fprintf(&b, "Environment=CLASHGO_BASE_DIR=%s\n", s.BaseDir)
	}
	b.WriteString("Nice=10\n")
	b.WriteString("IOSchedulingClass=idle\n")
	return b.String()
}

// TimerFile 生成 timer 单元内容。
func (s Spec) TimerFile() string {
	d := s.Interval
	if d <= 0 {
		d = DefaultInterval
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s. 执行 `clashgo sub schedule --off` 会删除本文件。\n", Marker)
	b.WriteString("[Unit]\n")
	fmt.Fprintf(&b, "Description=clashgo 每 %s 更新订阅\n\n", humanDuration(d))
	b.WriteString("[Timer]\n")
	if expr, ok := calendarExpr(d); ok {
		fmt.Fprintf(&b, "OnCalendar=%s\n", expr)
		// 关机期间错过的触发，开机后补跑一次
		b.WriteString("Persistent=true\n")
	} else {
		// 非整小时或不能整除 24 的间隔：从开机算起、按上次激活算下一次
		b.WriteString("OnBootSec=5min\n")
		fmt.Fprintf(&b, "OnUnitActiveSec=%s\n", unitDuration(d))
	}
	// 打散请求，避免所有机器整点一起打订阅接口
	b.WriteString("RandomizedDelaySec=10min\n")
	fmt.Fprintf(&b, "Unit=%s\n\n", ServiceName)
	b.WriteString("[Install]\n")
	b.WriteString("WantedBy=timers.target\n")
	return b.String()
}

// humanDuration 输出「6 小时」「2 天」这类中文描述。
func humanDuration(d time.Duration) string {
	switch {
	case d%(24*time.Hour) == 0:
		return fmt.Sprintf("%d 天", int(d/(24*time.Hour)))
	case d%time.Hour == 0:
		return fmt.Sprintf("%d 小时", int(d/time.Hour))
	case d%time.Minute == 0:
		return fmt.Sprintf("%d 分钟", int(d/time.Minute))
	default:
		return d.String()
	}
}

// unitDuration 输出 systemd 认识的时间写法（6h / 30min / 2d）。
func unitDuration(d time.Duration) string {
	switch {
	case d%(24*time.Hour) == 0:
		return fmt.Sprintf("%dd", int(d/(24*time.Hour)))
	case d%time.Hour == 0:
		return fmt.Sprintf("%dh", int(d/time.Hour))
	case d%time.Minute == 0:
		return fmt.Sprintf("%dmin", int(d/time.Minute))
	default:
		return fmt.Sprintf("%ds", int(d/time.Second))
	}
}

// ParseInterval 解析 `6h` / `2d` / `30m` 这类写法。
func ParseInterval(s string) (time.Duration, error) {
	s = strings.TrimSpace(s)
	if s == "" {
		return DefaultInterval, nil
	}
	// time.ParseDuration 支持 h/m/s，不支持 d，单独处理「N d」这种
	d := time.Duration(0)
	if strings.HasSuffix(s, "d") {
		days, derr := strconv.Atoi(strings.TrimSuffix(s, "d"))
		if derr != nil {
			return 0, fmt.Errorf("无法解析间隔 %q（支持 30m / 6h / 2d 这类写法）", s)
		}
		d = time.Duration(days) * 24 * time.Hour
	} else {
		var derr error
		d, derr = time.ParseDuration(s)
		if derr != nil {
			return 0, fmt.Errorf("无法解析间隔 %q（支持 30m / 6h / 2d 这类写法）", s)
		}
	}
	if d < 5*time.Minute {
		return 0, fmt.Errorf("间隔太短（%s），至少 5 分钟", d)
	}
	if d > 30*24*time.Hour {
		return 0, fmt.Errorf("间隔太长（%s），最多 30 天", d)
	}
	return d, nil
}

// writeFile 原子写：先写 .tmp 再 rename。
func writeFile(path, content string) (changed bool, err error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == content {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return false, err
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return false, err
	}
	return true, nil
}

// Install 写入两个单元文件、重载 systemd、启用并启动 timer。
func Install(s Spec) (changed bool, err error) {
	if !Available() {
		return false, fmt.Errorf("当前系统没有 systemd，无法使用 timer 定时任务")
	}
	svcPath, err := ServicePath()
	if err != nil {
		return false, err
	}
	tmrPath, err := TimerPath()
	if err != nil {
		return false, err
	}
	c1, err := writeFile(svcPath, s.ServiceFile())
	if err != nil {
		return false, err
	}
	c2, err := writeFile(tmrPath, s.TimerFile())
	if err != nil {
		return false, err
	}
	changed = c1 || c2

	// 无论文件是否变化都要 reload + enable，因为用户可能手动 disable 过
	if _, err := runUser("daemon-reload"); err != nil {
		return changed, fmt.Errorf("systemctl --user daemon-reload 失败: %w", err)
	}
	if _, err := runUser("enable", "--now", TimerName); err != nil {
		return changed, fmt.Errorf("启用 timer 失败: %w", err)
	}
	return changed, nil
}

// Remove 停用并删除 clashgo 生成的单元文件。
// 只删含 Marker 的文件，手写的同名 unit 不动。
func Remove() (removed bool, err error) {
	svcPath, err := ServicePath()
	if err != nil {
		return false, err
	}
	tmrPath, err := TimerPath()
	if err != nil {
		return false, err
	}
	// 先停掉，避免文件删了 timer 还在内存里跑
	if Available() {
		_, _ = runUser("disable", "--now", TimerName)
	}
	for _, p := range []string{tmrPath, svcPath} {
		data, rerr := os.ReadFile(p)
		if rerr != nil {
			continue
		}
		if !strings.Contains(string(data), Marker) {
			// 不是我们生成的，跳过
			continue
		}
		if rerr := os.Remove(p); rerr != nil {
			return removed, rerr
		}
		removed = true
	}
	if removed && Available() {
		if _, err := runUser("daemon-reload"); err != nil {
			return removed, fmt.Errorf("systemctl --user daemon-reload 失败: %w", err)
		}
	}
	return removed, nil
}

// Status 是定时任务的当前状态。
type Status struct {
	Installed bool   `json:"installed"`
	Enabled   bool   `json:"enabled"`
	Active    bool   `json:"active"`
	NextRun   string `json:"next_run"`
	LastRun   string `json:"last_run"`
	Service   string `json:"service_path"`
	Timer     string `json:"timer_path"`
	Interval  string `json:"interval"`
}

// Status 查询当前状态。Installed 只看文件，其余字段在 systemd 不可用时留空。
func Current() (Status, error) {
	var st Status
	svcPath, err := ServicePath()
	if err != nil {
		return st, err
	}
	tmrPath, err := TimerPath()
	if err != nil {
		return st, err
	}
	st.Service, st.Timer = svcPath, tmrPath
	if data, err := os.ReadFile(tmrPath); err == nil {
		st.Installed = true
		st.Interval = parseTimerInterval(string(data))
	}
	if !st.Installed || !Available() {
		return st, nil
	}
	if out, err := runUser("is-enabled", TimerName); err == nil {
		st.Enabled = strings.TrimSpace(out) == "enabled"
	}
	if out, err := runUser("is-active", TimerName); err == nil {
		st.Active = strings.TrimSpace(out) == "active"
	}
	// NextElapseUSecRealtime 是 systemd 245+ 的属性名，更老的只有 Monotonic 版本
	if out, err := runUser("show", "-p", "NextElapseUSecRealtime", "--value", TimerName); err == nil {
		v := strings.TrimSpace(out)
		if v != "" && v != "n/a" {
			st.NextRun = v
		}
	}
	if out, err := runUser("show", "-p", "LastTriggerUSec", "--value", TimerName); err == nil {
		v := strings.TrimSpace(out)
		if v != "" && v != "n/a" {
			st.LastRun = v
		}
	}
	return st, nil
}

// parseTimerInterval 从 timer 文件里抠出间隔描述，用于展示。
func parseTimerInterval(content string) string {
	for _, line := range strings.Split(content, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "OnCalendar=") {
			return strings.TrimPrefix(line, "OnCalendar=")
		}
		if strings.HasPrefix(line, "OnUnitActiveSec=") {
			return strings.TrimPrefix(line, "OnUnitActiveSec=")
		}
	}
	return ""
}

// LogCommand 返回查看定时任务日志的命令。
//
// 坑：用户单元（systemd --user）的日志落在**系统 journal** 里，
// `journalctl --user -u clashgo-sub-update.service` 会报 No journal files were found。
// 必须用 _SYSTEMD_USER_UNIT= 过滤才能看到。
func LogCommand() string {
	return fmt.Sprintf("journalctl _SYSTEMD_USER_UNIT=%s -f", ServiceName)
}
