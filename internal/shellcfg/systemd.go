package shellcfg

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// systemd 用户级 environment.d 的作用：
//
// rc 文件只在「shell 启动」时生效，覆盖不到
//   - systemd --user 启动的服务（GUI 应用、dbus 激活的进程）
//   - 已经开着的终端
//   - 非 shell 启动的程序
//
// environment.d/*.conf 由 systemd 的 user-environment-generator 解析，
// 对所有 systemd --user 会话及其子进程生效，因此这里是「其他终端也生效」的兜底。
const (
	// systemdEnvFile 是我们要托管的 environment.d 文件名。数字前缀决定覆盖顺序。
	systemdEnvFile = "90-clashgo.conf"
	// systemdEnvMarker 标记文件由 clashgo 生成，便于安全删除。
	systemdEnvMarker = "# Generated by clashgo. 执行 clashgo off 会删除本文件。"
)

// SystemdEnvPath 返回 environment.d 配置路径。
// 遵循 XDG_CONFIG_HOME，缺省 ~/.config/environment.d/90-clashgo.conf。
func SystemdEnvPath() (string, error) {
	base := os.Getenv("XDG_CONFIG_HOME")
	if base == "" {
		home, err := os.UserHomeDir()
		if err != nil || home == "" {
			return "", fmt.Errorf("无法确定用户主目录")
		}
		base = filepath.Join(home, ".config")
	}
	return filepath.Join(base, "environment.d", systemdEnvFile), nil
}

// SystemdAvailable 判断本机是否用 systemd 作为 init，且当前用户有 user 会话。
// 这只是「值不值得写 environment.d」的判断，不是错误条件。
func SystemdAvailable() bool {
	if _, err := os.Stat("/run/systemd/system"); err != nil {
		return false
	}
	if _, err := os.Stat("/usr/bin/systemctl"); err != nil {
		if _, err := os.Stat("/bin/systemctl"); err != nil {
			return false
		}
	}
	return true
}

// renderSystemdEnv 把 proxy.env 的内容改写成 environment.d 语法。
//
// environment.d 只接受 `KEY=VALUE`，不支持 export、变量引用、引号，
// 所以这里必须把 proxy.env 里 `HTTP_PROXY=$http_proxy` 这种间接引用展开成字面值。
func renderSystemdEnv(content string) string {
	vals := parseExports(content)
	// 保持与 proxy.env 相同的变量集合与顺序
	order := []string{
		"http_proxy", "HTTP_PROXY",
		"https_proxy", "HTTPS_PROXY",
		"all_proxy", "ALL_PROXY",
		"no_proxy", "NO_PROXY",
	}
	var b strings.Builder
	b.WriteString(systemdEnvMarker)
	b.WriteString("\n")
	for _, k := range order {
		v, ok := vals[k]
		if !ok {
			continue
		}
		// 展开 $lowercase 形式的上层变量引用
		if strings.HasPrefix(v, "$") {
			if resolved, ok := vals[strings.TrimPrefix(v, "$")]; ok {
				v = resolved
			}
		}
		b.WriteString(k)
		b.WriteString("=")
		b.WriteString(v)
		b.WriteString("\n")
	}
	return b.String()
}

// parseExports 从 proxy.env 文本里抽 export KEY=VALUE。不处理复杂 shell 语法，
// 因为我们自己生成的文件只有这一种形态。
func parseExports(content string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(content, "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "export ") {
			continue
		}
		kv := strings.TrimPrefix(line, "export ")
		idx := strings.Index(kv, "=")
		if idx <= 0 {
			continue
		}
		out[kv[:idx]] = kv[idx+1:]
	}
	return out
}

// WriteSystemdEnv 把代理变量写进 environment.d。proxyContent 是 proxy.env 的原文。
// 返回写入路径；本机不是 systemd 时返回空路径且不报错。
func WriteSystemdEnv(proxyContent string) (string, error) {
	if !SystemdAvailable() {
		return "", nil
	}
	path, err := SystemdEnvPath()
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", fmt.Errorf("创建 %s 失败: %w", filepath.Dir(path), err)
	}
	want := renderSystemdEnv(proxyContent)
	if old, err := os.ReadFile(path); err == nil && string(old) == want {
		return path, nil // 内容没变，不动文件，避免无谓地惊动 systemd
	}
	tmp := path + ".new"
	if err := os.WriteFile(tmp, []byte(want), 0o644); err != nil {
		return "", fmt.Errorf("写入 %s 失败: %w", tmp, err)
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return "", fmt.Errorf("替换 %s 失败: %w", path, err)
	}
	// 导入到当前用户会话，让已经登录的桌面/服务也能感知（失败不影响 shell 侧）
	_, _ = runQuiet("systemctl", "--user", "daemon-reload")
	return path, nil
}

// RemoveSystemdEnv 删除 clashgo 的 environment.d 配置。
// 只有当文件确实带我们的标记时才删，避免误删用户手写的同名文件。
func RemoveSystemdEnv() error {
	path, err := SystemdEnvPath()
	if err != nil {
		return err
	}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("读取 %s 失败: %w", path, err)
	}
	if !strings.Contains(string(data), systemdEnvMarker) {
		return nil // 不是我们写的，不碰
	}
	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("删除 %s 失败: %w", path, err)
	}
	_, _ = runQuiet("systemctl", "--user", "daemon-reload")
	return nil
}

// contentHash 仅供测试与诊断使用。
func contentHash(s string) string {
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:8])
}

// runQuiet 跑一条命令并返回 stdout；出错返回空。与 netutil 里的同名函数区别是
// 这里允许 stderr 直通（systemctl 的告警就该让用户看见）。
func runQuiet(name string, args ...string) (string, error) {
	out, err := exec.Command(name, args...).Output()
	if err != nil {
		return "", err
	}
	return string(out), nil
}
